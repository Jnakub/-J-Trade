#   จัดกลุ่ม Swing High+Low ที่ราคาใกล้กัน (ภายใน KEY_LEVEL_PROXIMITY) เป็น "โซน" เดียวกัน
#   โซนที่โดนแตะ >= KEY_LEVEL_MIN_TOUCHES ครั้ง ถือว่าเป็นแนวรับ/ต้านใหญ่จริง
