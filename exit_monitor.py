            keep_str = f"{r['keep_pct']}%"
            keep_color = RED if r["keep_pct"] <= 0 else (YELLOW if r["keep_pct"] < 100 else GREEN)
            print(f"  กฎ {r['no']} — {r['name']:<20} {status}   ควรเหลือ {keep_color}{keep_str}{RESET}")
            print(f"       {DIM}เงื่อนไข: {r['cond']}{RESET}")

