    print(f"  Entry Date/Time   : {entry_str}")
    print(f"  Current Date/Time : {now_str}")
    # แสดง 2 ตัวเลขเมื่อไม่เท่ากัน — กฎคนละข้อใช้คนละตัว (ข้อ 0 = ปฏิทิน, ข้อ 4 = วันทำการ)
