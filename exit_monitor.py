    print("=" * 62)
    print(_b(f"  {m['symbol']}  ticket #{m['ticket']}  ({dir_color(m['direction'])})"))
    print("=" * 62)
    entry_str = m["entry_time"].strftime("%d/%m/%Y %H:%M")
