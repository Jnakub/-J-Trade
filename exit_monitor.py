    if invalidated:
        base_keep_pct = 0
    elif trend_broken_partial:
        base_keep_pct = trend_keep_pct   # เตือนภัย ยังไม่ฟันธง 100% — ปิดกันไว้ก่อนตามระดับความต่อเนื่อง (75/50)
    elif slow_trade:
        base_keep_pct = SLOW_TRADE_KEEP
