        print(f"\n{'#' * 62}")
        print(f"  รอบใหม่  {now}")
        print(f"{'#' * 62}")

        try:
            scan_once()
        except Exception as exc:
            print(_r(f"[ERROR] {exc}"))
            log.error("run_monitor scan_once ERROR", exc_info=True)
